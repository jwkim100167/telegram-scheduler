# 부정어 (앞에 붙으면 반전): "하락하지 않음" → 양성
_NEGATION_PREFIX = ["않", "아니", "없", "못", "비", "무", "불"]


def _count_keywords(text: str, keywords: list[str]) -> int:
    count = 0
    for kw in keywords:
        idx = text.find(kw)
        while idx != -1:
            # 앞 2글자 이내에 부정어가 있으면 무효화
            prefix = text[max(0, idx - 2): idx]
            if not any(neg in prefix for neg in _NEGATION_PREFIX):
                count += 1
            idx = text.find(kw, idx + 1)
    return count


def analyze_sentiment(text: str) -> int:
    """
    text에서 감성 점수를 반환한다.
    +1: 긍정, -1: 부정, 0: 중립
    """
    if not text:
        return 0
    t = text.lower()  # 소문자 통일 (영문 혼용 대비)
    pos = _count_keywords(t, POSITIVE)
    neg = _count_keywords(t, NEGATIVE)
    score = pos - neg
    if score > 0:
        return 1
    if score < 0:
        return -1
    return 0
